let currentLang = 'en';

export function setLanguage(lang) {
  if (lang === 'vi' || lang === 'en') {
    currentLang = lang;
    localStorage.setItem('readify_lang', lang);
    document.documentElement.lang = lang;
  }
}

export function getLanguage() {
  const saved = localStorage.getItem('readify_lang');
  if (saved === 'vi' || saved === 'en') {
    currentLang = saved;
  }
  return currentLang;
}

export function t(path, replacements = {}) {
  const keys = path.split('.');
  let result = translations[currentLang];
  for (const k of keys) {
    if (result && result[k] !== undefined) {
      result = result[k];
    } else {
      // Fallback to English if translation missing
      let fallback = translations['en'];
      for (const fk of keys) {
        if (fallback && fallback[fk] !== undefined) {
          fallback = fallback[fk];
        } else {
          return path;
        }
      }
      result = fallback;
      break;
    }
  }

  if (typeof result === 'string') {
    let str = result;
    for (const [rKey, rVal] of Object.entries(replacements)) {
      str = str.replace(new RegExp(`\\{${rKey}\\}`, 'g'), rVal);
    }
    return str;
  }
  return result || path;
}
